"""Dependency-free test runner (pytest also works). Writes docs/TEST_RESULTS.md from the actual run."""
import importlib
import os
import sys
import time
import traceback
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tests"))
mod = importlib.import_module("test_feeshield")
tests = [(n, f) for n, f in vars(mod).items() if n.startswith("test_") and callable(f)]
rows, failed = [], 0
t0 = time.time()
for name, fn in tests:
    try:
        fn()
        rows.append((name, "PASS", ""))
    except Exception:
        failed += 1
        rows.append((name, "FAIL", traceback.format_exc(limit=3)))
elapsed = time.time() - t0
for n, s, tb in rows:
    print(f"{s}  {n}")
    if tb:
        print(tb)
summary = f"{len(tests) - failed}/{len(tests)} passed in {elapsed:.2f}s"
print("\n" + summary)
with open(os.path.join(ROOT, "docs", "TEST_RESULTS.md"), "w", encoding="utf-8") as fh:
    fh.write(f"# Test results (generated by `python run_tests.py`)\n\nRun at: {datetime.now(timezone.utc).isoformat()}\n"
             f"Python: {sys.version.split()[0]}\n\n**{summary}**\n\n| Test | Result |\n|---|---|\n")
    for n, s, _ in rows:
        fh.write(f"| {n} | {s} |\n")
    for n, s, tb in rows:
        if tb:
            fh.write(f"\n### Failure: {n}\n```\n{tb}\n```\n")
sys.exit(1 if failed else 0)
